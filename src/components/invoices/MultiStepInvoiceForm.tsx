import React, { useState, useEffect } from 'react';
import {
  Modal,
  ModalOverlay,
  ModalContent,
  ModalHeader,
  ModalBody,
  ModalFooter,
  ModalCloseButton,
  VStack,
  HStack,
  FormControl,
  FormLabel,
  Input,
  Textarea,
  Select,
  Button,
  useToast,
  Text,
  Divider,
  Box,
  Progress,
  Card,
  CardBody,
  Badge,
  useColorModeValue
} from '@chakra-ui/react';
import { useMutation, useQuery } from 'convex/react';
import { api } from '../../../convex/_generated/api';
import { Id } from '../../../convex/_generated/dataModel';
import { useAuth } from '../../contexts/shared/AuthContext';
import { formatCurrencyDisplay } from '../../utils/invoiceCurrencyUtils';

// Step Components
import Step1CustomerInfo from './steps/Step1CustomerInfo';
import Step2Items from './steps/Step2Items';
import Step3Financial from './steps/Step3Financial';
import Step4Review from './steps/Step4Review';

interface InvoiceItem {
  id: string;
  description: string;
  description_arabic: string;
  quantity: number;
  unit: string;
  unit_price: number;
  discount_percentage: number;
  vat_rate: number;
  supply_type: string;
  supply_type_arabic: string;
  is_zero_rated: boolean;
  is_exempt: boolean;
  inventory_id?: Id<"inventory">;
  sku?: string;
  purchase_price?: number;
  markup_amount?: number;
  inventory_name?: string;
  notes?: string;
  total_price?: number;
  vat_amount?: number;
}

interface InvoiceFormData {
  // Step 1: Customer & Basic Info
  customer_id: string;
  customer_name: string;
  invoice_number?: string; // Auto-generated, optional
  invoice_date: string;
  due_date: string;
  description: string;
  terms_conditions: string;
  notes: string;
  
  // Step 2: Items
  items: InvoiceItem[];
  
  // Step 3: Financial
  currency: string;
  markup_percentage: number;
  subtotal: number;
  vat_rate: number;
  vat_amount: number;
  total_amount: number;
  
  // Step 4: Review & Submit
  status: string;
}

interface MultiStepInvoiceFormProps {
  isOpen: boolean;
  onClose: () => void;
  quotationId?: Id<"quotations">;
  onSuccess?: (invoiceId: Id<"invoices">) => void;
}

const MultiStepInvoiceForm: React.FC<MultiStepInvoiceFormProps> = ({
  isOpen,
  onClose,
  quotationId,
  onSuccess
}) => {
  const { selectedOrganization } = useAuth();
  const toast = useToast();
  const createInvoice = useMutation(api.invoiceManagement.createInvoice);
  
  const [currentStep, setCurrentStep] = useState(1);
  // Generate a preview invoice number (will be replaced by backend)
  const generatePreviewInvoiceNumber = () => {
    const currentYear = new Date().getFullYear();
    const timestamp = Date.now().toString().slice(-4); // Last 4 digits of timestamp
    return `INV-${currentYear}-${timestamp}`;
  };

  const [formData, setFormData] = useState<InvoiceFormData>({
    customer_id: '',
    customer_name: '',
    invoice_number: generatePreviewInvoiceNumber(), // Preview invoice number
    invoice_date: new Date().toISOString().split('T')[0],
    due_date: new Date(Date.now() + 30 * 24 * 60 * 60 * 1000).toISOString().split('T')[0],
    description: '',
    terms_conditions: '',
    notes: '',
    items: [],
    currency: 'SAR',
    markup_percentage: 0,
    subtotal: 0,
    vat_rate: 15,
    vat_amount: 0,
    total_amount: 0,
    status: 'draft'
  });

  const [isLoading, setIsLoading] = useState(false);

  const steps = [
    { number: 1, title: 'Customer & Basic Info', description: 'Select customer and basic invoice details' },
    { number: 2, title: 'Items & Pricing', description: 'Add invoice items and pricing' },
    { number: 3, title: 'Financial Information', description: 'Set currency, markup, and calculations' },
    { number: 4, title: 'Review & Submit', description: 'Review and submit invoice' }
  ];

  const progress = (currentStep / steps.length) * 100;

  const handleNext = () => {
    if (currentStep < steps.length) {
      setCurrentStep(currentStep + 1);
    }
  };

  const handlePrevious = () => {
    if (currentStep > 1) {
      setCurrentStep(currentStep - 1);
    }
  };

  const handleSubmit = async () => {
    if (!selectedOrganization) {
      toast({
        title: 'Error',
        description: 'No organization selected',
        status: 'error',
        duration: 3000,
        isClosable: true,
      });
      return;
    }

    setIsLoading(true);
    try {
      const invoiceId = await createInvoice({
        organization_id: selectedOrganization,
        customer_id: formData.customer_id as Id<"customers">,
        invoice_number: formData.invoice_number || "TEMP", // Will be auto-generated by backend
        invoice_type: "standard",
        status: formData.status,
        subtotal: formData.subtotal,
        total_vat: formData.vat_amount,
        grand_total: formData.total_amount,
        currency: formData.currency,
        vat_rate: formData.vat_rate,
        customer_name: formData.customer_name,
        customer_address: "Default Address", // TODO: Get from customer data
        payment_terms: formData.terms_conditions || "Net 30",
        invoice_date: formData.invoice_date,
        due_date: formData.due_date,
        notes: formData.notes,
        created_by: 'system', // TODO: Get from auth context
        items: formData.items.map(item => ({
          description: item.description,
          description_arabic: item.description_arabic || item.description, // Use English description as fallback
          quantity: item.quantity,
          unit: item.unit,
          unit_price: item.unit_price,
          discount_percentage: item.discount_percentage,
          vat_rate: item.vat_rate,
          supply_type: item.supply_type,
          supply_type_arabic: item.supply_type_arabic,
          is_zero_rated: item.is_zero_rated,
          is_exempt: item.is_exempt,
          inventory_id: item.inventory_id,
          sku: item.sku,
          purchase_price: item.purchase_price,
          markup_amount: item.markup_amount,
          inventory_name: item.inventory_name,
          notes: item.notes
        }))
      });

      toast({
        title: 'Success',
        description: 'Invoice created successfully',
        status: 'success',
        duration: 3000,
        isClosable: true,
      });

      onSuccess?.(invoiceId);
      onClose();
    } catch (error) {
      console.error('Error creating invoice:', error);
      toast({
        title: 'Error',
        description: 'Failed to create invoice',
        status: 'error',
        duration: 3000,
        isClosable: true,
      });
    } finally {
      setIsLoading(false);
    }
  };

  const renderStep = () => {
    switch (currentStep) {
      case 1:
        return (
          <Step1CustomerInfo
            formData={formData}
            setFormData={setFormData}
            quotationId={quotationId}
          />
        );
      case 2:
        return (
          <Step2Items
            formData={formData}
            setFormData={setFormData}
          />
        );
      case 3:
        return (
          <Step3Financial
            formData={formData}
            setFormData={setFormData}
          />
        );
      case 4:
        return (
          <Step4Review
            formData={formData}
            setFormData={setFormData}
          />
        );
      default:
        return null;
    }
  };

  const canProceed = () => {
    switch (currentStep) {
      case 1:
        return formData.customer_id && formData.invoice_number && formData.invoice_date;
      case 2:
        return formData.items.length > 0;
      case 3:
        return formData.currency && formData.total_amount > 0;
      case 4:
        return true;
      default:
        return false;
    }
  };

  return (
    <Modal isOpen={isOpen} onClose={onClose} size="full" scrollBehavior="inside">
      <ModalOverlay />
      <ModalContent maxH="95vh" maxW="95vw" w="95vw">
        <ModalHeader>
          <VStack align="stretch" spacing={2}>
            <Text fontSize="xl" fontWeight="bold">
              Create Invoice - Step {currentStep} of {steps.length}
            </Text>
            <Text fontSize="sm" color="gray.500">
              {steps[currentStep - 1].title}: {steps[currentStep - 1].description}
            </Text>
            <Progress value={progress} colorScheme="blue" size="sm" />
          </VStack>
        </ModalHeader>
        <ModalCloseButton />
        
        <ModalBody>
          <VStack spacing={6} align="stretch">
            {/* Step Navigation */}
            <HStack spacing={4} justify="center">
              {steps.map((step) => (
                <VStack key={step.number} spacing={1}>
                  <Box
                    w={8}
                    h={8}
                    borderRadius="full"
                    bg={currentStep >= step.number ? "blue.500" : "gray.200"}
                    color={currentStep >= step.number ? "white" : "gray.600"}
                    display="flex"
                    alignItems="center"
                    justifyContent="center"
                    fontSize="sm"
                    fontWeight="bold"
                  >
                    {step.number}
                  </Box>
                  <Text fontSize="xs" textAlign="center" maxW={20}>
                    {step.title}
                  </Text>
                </VStack>
              ))}
            </HStack>
            
            <Divider />
            
            {/* Step Content */}
            {renderStep()}
          </VStack>
        </ModalBody>
        
        <ModalFooter>
          <HStack spacing={3}>
            <Button
              variant="ghost"
              onClick={onClose}
              isDisabled={isLoading}
            >
              Cancel
            </Button>
            
            {currentStep > 1 && (
              <Button
                variant="outline"
                onClick={handlePrevious}
                isDisabled={isLoading}
              >
                Previous
              </Button>
            )}
            
            {currentStep < steps.length ? (
              <Button
                colorScheme="blue"
                onClick={handleNext}
                isDisabled={!canProceed() || isLoading}
              >
                Next
              </Button>
            ) : (
              <Button
                colorScheme="green"
                onClick={handleSubmit}
                isLoading={isLoading}
                loadingText="Creating..."
                isDisabled={!canProceed()}
              >
                Create Invoice
              </Button>
            )}
          </HStack>
        </ModalFooter>
      </ModalContent>
    </Modal>
  );
};

export default MultiStepInvoiceForm;
